#!/usr/bin/env python3
"""Pack the extension's Goal Zone / Red Zone modules + brain.js into one classic script for the TV app.
Usage: bundle.py <extension dir> <out file>
Each module becomes  __mods['name'] = (function(){ ...; return {exports}; })();  so names never clash."""
import re, sys, pathlib
ext, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
MODS = ['nhl', 'cfb', 'director-core', 'cfb-director']
parts = ["// Generated by tools/bundle.py from the Game Day Multiview extension. Do not edit by hand.",
         "var __mods = {};",
         "if (typeof structuredClone !== 'function') { window.structuredClone = (v) => JSON.parse(JSON.stringify(v)); }"]
def convert(name, src):
    exports = []
    def imp(m):
        names = [n.strip() for n in m.group(1).split(',') if n.strip()]
        names = [re.sub(r'^(\w+)\s+as\s+(\w+)$', r'\1: \2', n) for n in names]
        return "const { %s } = __mods['%s'];" % (', '.join(names), m.group(2))
    src = re.sub(r"import\s*\{([^}]*)\}\s*from\s*'\./([\w-]+)\.js';", imp, src)
    assert 'import ' not in re.sub(r'//.*', '', src).split('\n')[0:0] or True
    def exp(m):
        exports.append(m.group(2))
        return m.group(1)
    src = re.sub(r'^export\s+((?:async\s+)?function\*?\s+(\w+))', exp, src, flags=re.M)
    src = re.sub(r'^export\s+((?:const|let|var)\s+(\w+))', exp, src, flags=re.M)
    assert not re.search(r'^\s*export\b', src, flags=re.M), f'unhandled export in {name}'
    assert not re.search(r'^\s*import\b', src, flags=re.M), f'unhandled import in {name}'
    return "__mods['%s'] = (function () {\n%s\nreturn { %s };\n})();" % (name, src, ', '.join(exports))
for m in MODS:
    parts.append(convert(m, (ext / f'{m}.js').read_text()))
brain = (pathlib.Path(__file__).resolve().parent.parent / 'app/src/main/assets/brain/brain.js').read_text()
parts.append("(function () {\n" + brain + "\n})();")
out.write_text('\n\n'.join(parts) + '\n')
print('wrote', out, len(out.read_text()), 'bytes')
